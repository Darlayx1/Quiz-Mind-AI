import assert from 'node:assert/strict';
import { renderToStaticMarkup } from 'react-dom/server';
import { createElement } from 'react';
import { QUESTION_TYPES } from '../src/types/quiz.js';
import { activeQuestionTypes, allocatedCount, compositionError, defaultComposition, effectiveCount, equalDistribution, maximumPoints, typeSettingsError } from '../src/questionComposition.js';
import { QuestionComposition } from '../src/components/QuestionComposition.js';
import { QuestionScoring } from '../src/components/QuestionScoring.js';
import { LanguageStyleSelector } from '../src/components/LanguageStyleSelector.js';
import { DurationControl } from '../src/components/DurationControl.js';
import { defaultEvaluationSettings } from '../src/evaluationSettings.js';
import { normalizeQuizConfig, quizTimerSeconds } from '../src/quizConfig.js';
import { restoreComposerDraft } from '../src/composerDraft.js';
import { configurationState, buildComposerConfig } from '../src/configurationState.js';
import { effectiveLanguageStyle, LANGUAGE_STYLES } from '../src/languageStyles.js';
import { emptyWorkspace } from '../src/workspace/types.js';

for (let total = 7; total <= 100; total++) {
  const distribution = equalDistribution([...QUESTION_TYPES].reverse(), total);
  assert.equal(Object.values(distribution).reduce((sum, n) => sum + n!, 0), total);
  const mixed = { ...defaultComposition, mode: 'mixed' as const, distribution };
  assert.equal(effectiveCount(mixed, 999), total); assert.equal(compositionError(mixed, NaN), '');
  assert.equal(normalizeQuizConfig({ topic: 'Fixture', questionCount: total, questionDistribution: distribution }).questionCount, total);
}
const mixed = { ...defaultComposition, mode: 'mixed' as const, distribution: { single_choice: 3, essay: 4 }, points: { essay: 4 }, times: { essay: 0 } };
assert.equal(allocatedCount(mixed), 7); assert.deepEqual(activeQuestionTypes(mixed), ['single_choice', 'essay']);
assert.equal(compositionError(mixed, 10), ''); assert.equal(maximumPoints(mixed, 999), 19);
assert.match(compositionError({ ...mixed, distribution: {} }, 10), /minimal satu/);
assert.match(compositionError({ ...mixed, distribution: { essay: 101 } }, 10), /0–100/);
assert.match(compositionError({ ...mixed, distribution: { essay: 60, matching: 50 } }, 100), /melebihi/);
assert.match(compositionError({ ...mixed, distribution: { essay: 1.5 } }, 10), /bilangan bulat/);
assert.match(compositionError(defaultComposition, NaN), /bilangan bulat/);
assert.match(compositionError({ ...defaultComposition, type: 'unknown' as any }, 10), /tipe soal/);
const single = { ...defaultComposition, singleCounts: { single_choice: 13, essay: 6 }, points: { single_choice: 2, essay: 4 } };
assert.equal(effectiveCount(single, 10), 13); assert.equal(effectiveCount({ ...single, type: 'essay' }, 10), 6);
assert.equal(maximumPoints(single, 10), 26);
assert.match(typeSettingsError({ ...mixed, points: { essay: 0 } }, 'essay', false), /Bobot/);
assert.match(typeSettingsError({ ...mixed, points: { essay: 1.5 } }, 'essay', false), /bilangan bulat/);
assert.match(typeSettingsError({ ...mixed, times: { essay: 601 } }, 'essay', true), /Waktu/);
assert.equal(typeSettingsError({ ...mixed, times: { essay: 601 } }, 'essay', false), '');
const markup = (value: typeof defaultComposition, timed = false) => renderToStaticMarkup(createElement(QuestionComposition, { value, onChange() {}, count: 10, timed, defaultSeconds: 90 }));
assert.equal((markup(single).match(/class="composition-row/g) || []).length, 2); // wrapper + active row
assert.ok(!markup(single).includes('Contoh soal')); assert.ok(!markup(single).includes('question-gallery'));
assert.ok(markup(single).includes('aria-haspopup="dialog"'));
assert.ok(!markup(single).includes('id="points-'));
assert.equal((markup(mixed).match(/id="points-/g) || []).length, 7);
const defaultStyleMarkup = renderToStaticMarkup(createElement(LanguageStyleSelector, { value: '', custom: false, customText: '', onChange() {} }));
assert.ok(defaultStyleMarkup.includes('id="language-style"'));
assert.ok(defaultStyleMarkup.includes('Biarkan kosong'));
assert.ok(defaultStyleMarkup.includes('type="text"'));
assert.ok(defaultStyleMarkup.includes('Pilih preset gaya bahasa'));
assert.ok(!defaultStyleMarkup.includes('<textarea'));
const durationMarkup = (sequential: boolean, unlimited: boolean, valid = true) => renderToStaticMarkup(createElement(DurationControl, { sequential, unlimited, valid, value: sequential ? '90' : '20', onChange() {}, onUnlimitedChange() {} }));
assert.ok(durationMarkup(false, false).includes('30 menit'));
assert.ok(durationMarkup(true, false).includes('180 detik'));
assert.ok(durationMarkup(true, false).includes('Durasi kustom per soal'));
assert.ok(!durationMarkup(true, true).includes('id="quiz-duration"'));
assert.ok(!durationMarkup(true, true).includes('class="duration-preset"'));
assert.ok(durationMarkup(true, true).includes('Tanpa batas waktu'));
assert.ok(durationMarkup(true, false, false).includes('aria-invalid="true"'));
assert.equal((markup(mixed).match(/class="composition-row /g) || []).length, 7);
assert.equal((markup(mixed, true).match(/id="time-(?!help-)/g) || []).length, 7);
assert.equal((markup(mixed, false).match(/id="time-(?!help-)/g) || []).length, 0);
assert.ok(!markup(mixed).includes('id="quiz-count"'));
assert.ok(markup(mixed).includes('19')); assert.ok(markup(mixed).includes('min="0"'));
const scoring = (type: typeof QUESTION_TYPES[number]) => renderToStaticMarkup(createElement(QuestionScoring, { value: { ...defaultComposition, type }, onChange() {}, evaluator: defaultEvaluationSettings, onOpen() {} }));
assert.ok(!scoring('single_choice').includes('Berikan kredit parsial'));
assert.ok(scoring('multiple_select').includes('Berikan kredit parsial'));
assert.ok(scoring('ordering').includes('Berikan kredit parsial'));
assert.ok(scoring('matching').includes('per pasangan'));
assert.ok(scoring('essay').includes('Kelola Evaluasi AI'));
assert.ok(!scoring('essay').includes('Penilaian &amp; bobot'));
const preferences = emptyWorkspace().preferences;
const draft = restoreComposerDraft({ topic: 'Astronomi', composition: mixed, totalMinutes: '20', perQuestionSeconds: '90' });
assert.equal(configurationState(draft).count, 7);
assert.equal(buildComposerConfig(draft, preferences).questionCount, 7);
assert.equal(quizTimerSeconds(buildComposerConfig(draft, preferences)), 1200);
const sequential = { ...draft, displayMode: 'sequential' as const };
assert.equal(configurationState(sequential).timerLabel, 'Bervariasi per tipe');
assert.equal(buildComposerConfig(sequential, preferences).timePerQuestionByType?.essay, 0);
assert.equal(quizTimerSeconds(buildComposerConfig(sequential, preferences)), 90);
const unlimited = { ...sequential, unlimited: true };
assert.equal(configurationState(unlimited).timerLabel, 'Tanpa batas');
assert.equal(quizTimerSeconds(buildComposerConfig(unlimited, preferences)), 0);
assert.equal(buildComposerConfig(unlimited, preferences).timePerQuestionByType, undefined);
assert.deepEqual(restoreComposerDraft(JSON.parse(JSON.stringify(unlimited))).composition, mixed);
assert.equal(configurationState({ ...unlimited, unlimited: false }).timerLabel, 'Bervariasi per tipe');
assert.equal(configurationState({ ...draft, composition: { ...single, times: { single_choice: 0 } }, displayMode: 'sequential' }).timerLabel, 'Tanpa batas');
assert.equal(configurationState({ ...draft, composition: { ...mixed, times: { essay: 601 } }, displayMode: 'sequential' }).timerLabel, '—');
for (const bad of ['', '0', '-1', '121', '1.5']) assert.ok(configurationState({ ...draft, totalMinutes: bad }).error);
for (const bad of ['', '0', '-1', '601', '1.5']) assert.ok(configurationState({ ...sequential, perQuestionSeconds: bad }).error);
assert.throws(() => buildComposerConfig({ ...draft, composition: { ...mixed, points: { essay: 21 } } }, preferences), /Bobot/);
assert.equal(LANGUAGE_STYLES.length, 20); assert.equal(new Set(LANGUAGE_STYLES.map(([label]) => label)).size, 20);
for (const [label, definition] of LANGUAGE_STYLES) {
  const styled = buildComposerConfig({ ...draft, languageStyle: label, languageStyleMode: 'preset' }, preferences);
  assert.ok(styled.languageStyle?.includes(definition)); assert.equal(styled.questionCount, 7);
  assert.deepEqual(styled.questionDistribution, mixed.distribution); assert.deepEqual(styled.pointsByType, mixed.points); assert.equal(styled.difficulty, draft.difficulty);
}
assert.equal(effectiveLanguageStyle('Mon style à moi'), 'Mon style à moi');
assert.equal(configurationState({ ...draft, languageStyle: 'Gaya lama saya' }).customStyle, true);
assert.equal(configurationState({ ...draft, languageStyleMode: 'custom', languageStyle: '' }).customStyle, false);
assert.ok(buildComposerConfig({ ...draft, languageStyleMode: 'custom', languageStyle: '' }, preferences).languageStyle?.startsWith('Baku & akademis'));
assert.ok(buildComposerConfig({ ...draft, languageStyleMode: 'preset', languageStyle: '', languageStylePreset: 'Teknis & presisi' }, preferences).languageStyle?.startsWith('Teknis & presisi'));
const restored = restoreComposerDraft(JSON.parse(JSON.stringify({ ...draft, composition: single, languageStyleMode: 'preset', customLanguageStyle: 'Teks kustom tersimpan' })));
assert.deepEqual(restored.composition, single); assert.equal(restored.customLanguageStyle, 'Teks kustom tersimpan');
console.log('PASS: derived mixed totals 7–100, seven compact rows, active single selector, integrated weights/times, independent type counts, contextual grading, mode timers/overrides/unlimited, 20 effective styles, validation and legacy draft restoration.');
